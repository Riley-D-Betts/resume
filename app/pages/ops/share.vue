          :disabled="minting || label.trim().length === 0"
        >
          {{ minting ? '... MINTING' : 'MINT LINK' }}
        </button>
      </form>

      <p v-if="mintFault" class="sh__fault" role="alert">MINT FAULT // {{ mintFault.toUpperCase() }}</p>
      <div v-if="minted" class="sh__minted">
        <span class="label">LINK</span>
        <code class="sh__url" data-testid="share-minted-url">{{ minted.url }}</code>
        <button type="button" class="sh__btn label" data-testid="share-copy" @click="copy(minted.url, 'minted')">
          {{ copied === 'minted' ? 'COPIED' : 'COPY' }}
        </button>
      </div>
      <p class="sh__note label">
        THE LABEL IS THE ONLY NAME THIS FEATURE EVER RECORDS · EVERY OTHER OPENER IS DESCRIBED BY ORGANIZATION, COUNTRY AND DEVICE
      </p>
    </Panel>

    <p v-if="error" class="sh__fault">{{ opsFault(error, 'share') }}</p>
    <p v-else-if="!data && status === 'pending'" class="sh__poll label">... POLLING</p>

    <template v-if="data">
      <Panel title="SHARE LINKS // WHERE THE RÉSUMÉ WENT">
        <DataTable
          :columns="columns"
          :rows="rows"
          row-key="token"
          row-testid="share-row"
          :sort="{ key: 'createdAt', dir: 'desc' }"
          empty="NO DATA // SHARE LINKS"
          dense
        >
          <template #cell-token="{ row }">
            <button type="button" class="sh__tok" :class="{ 'sh__tok--on': selected === row.token }" @click.stop="toggle(String(row.token))">
              {{ row.token }}
            </button>
          </template>
          <template #cell-platforms="{ value }">
            <span class="sh__chips">
              <span v-for="p in chips(value)" :key="p" class="sh__chip sh__chip--on label">{{ p }}</span>
              <span v-if="chips(value).length === 0">—</span>
            </span>
          </template>
          <template #cell-orgs="{ value }">
            <span class="sh__chips">
              <span v-for="o in chips(value)" :key="o" class="sh__chip label">{{ o }}</span>
              <span v-if="chips(value).length === 0">—</span>
            </span>
          </template>
          <template #cell-countries="{ value }">
            <span class="sh__chips">
              <span v-for="c in chips(value)" :key="c" class="sh__chip label">{{ c }}</span>
              <span v-if="chips(value).length === 0">—</span>
            </span>
          </template>
          <template #cell-forwarded="{ row, value }">
            <span v-if="value" class="sh__fwd label">FORWARDED // {{ evidence(row) }}</span>
            <span v-else class="sh__quiet">—</span>
          </template>
          <template #cell-state="{ row }">
            <span class="sh__state label" :class="{ 'sh__state--off': row.revoked }">{{ row.state }}</span>
            <button type="button" class="sh__btn label" @click.stop="setRevoked(String(row.token), !row.revoked)">
              {{ row.revoked ? 'RESTORE' : 'REVOKE' }}
            </button>
          </template>
        </DataTable>
        <p class="sh__note label">
          PEOPLE = DISTINCT VISITOR IDENTITIES AMONG THE SESSIONS CARRYING THE LINK · A REVOKED LINK IS STILL RECORDED, THAT IS THE POINT
        </p>
      </Panel>

      <template v-if="selected">
        <p v-if="detailFault" class="sh__fault">{{ opsFault(detailFault, 'share link') }}</p>
        <p v-else-if="detailLoading && !detail" class="sh__poll label">... POLLING</p>

        <template v-if="detail && selectedLink">
          <Panel :title="`LINK ${selectedLink.token} // ${selectedLink.label.toUpperCase()}`" teal>
            <div class="sh__head">
              <code class="sh__url">{{ selectedLink.url }}</code>
              <button type="button" class="sh__btn label" @click="copy(selectedLink.url, 'detail')">
                {{ copied === 'detail' ? 'COPIED' : 'COPY' }}
              </button>
              <span class="sh__state label" :class="{ 'sh__state--off': selectedLink.revoked }">
                {{ selectedLink.revoked ? 'REVOKED' : 'LIVE' }}
              </span>
              <span v-if="selectedLink.channel" class="sh__chip label">{{ selectedLink.channel }}</span>
            </div>
            <p v-if="selectedLink.note" class="sh__prose">{{ selectedLink.note }}</p>
            <p class="sh__verdict label">
              <template v-if="selectedLink.forwarded">
                FORWARDED, RECIPIENT UNKNOWN // {{ evidence({ ...selectedLink }) }} · ONLY {{ selectedLink.label.toUpperCase() }} WAS NAMED BY YOU
              </template>
              <template v-else-if="selectedLink.opens > 0">
                NO EVIDENCE OF FORWARDING // {{ evidence({ ...selectedLink }) || 'PREVIEW FETCHES ONLY' }}
              </template>
              <template v-else>
                NEVER OPENED
              </template>
            </p>
          </Panel>

          <Panel title="HITS // EVERY REQUEST THAT CARRIED THE LINK">
            <DataTable
              :columns="hitColumns"
              :rows="hitRows"
              row-key="id"
              row-testid="share-hit-row"
              :sort="{ key: 'ts', dir: 'desc' }"
              empty="NO DATA // HITS"
              dense
              :limit="50"
            >
              <template #cell-kind="{ value }">
                <span class="sh__kind label" :class="`sh__kind--${String(value)}`">{{ String(value).toUpperCase() }}</span>
              </template>
            </DataTable>
            <p class="sh__note label">NO IP AND NO RAW USER AGENT IS STORED HERE · PLATFORM COMES FROM A NAMED PREVIEW-BOT TABLE</p>
          </Panel>

          <Panel title="SESSIONS // WHAT THE LINK PRODUCED">
            <DataTable
              :columns="sessionColumns"
              :rows="sessionRows"
              row-key="sid"
              row-testid="share-session-row"
              :sort="{ key: 'started_at', dir: 'desc' }"
              :row-to="sessionTo"
              empty="NO DATA // SESSIONS"
              dense
            />
            <p class="sh__note label">ATTRIBUTED THROUGH SESSION_NET.SHARE_TOKEN — THE COOKIE THE DOCUMENT REQUEST SET, FIRST WRITE WINS</p>
          </Panel>
        </template>
      </template>
    </template>
  </div>
</template>

