<script setup lang="ts">
import type { ShareHitRow, ShareLinkDetail, ShareLinkRow, ShareLinks, ShareMintResult } from '#shared/analytics/ops'
import type { DataColumn } from '~/components/ops/DataTable.vue'
import type { OpsFetchError } from '~/composables/useOpsFetch'
import { copyText } from '~/utils/csv'

definePageMeta({ layout: 'ops', middleware: 'ops-auth' })

useHead({ title: 'OPS // SHARE' })

const fmt = useOpsFormat()
const { linkTo } = useOpsFilters()

type Row = Record<string, unknown>

/**
 * SHARE — one link per named recipient, and honest evidence of circulation.
 *
 * There is no forwarding tree here on purpose: no URL rewriting, no
 * per-visitor token, no chain. A link opened by several distinct people is
 * reported as FORWARDED with the recipient UNKNOWN, which is the true state of
 * knowledge. The only name on this page is the label the owner typed himself.
 *
 * The view is not windowed by the filter bar: a link is a thing, not a period.
 */
const { data, status, error, refresh } = useOpsFetch<ShareLinks>('/api/ops/share')

// ------------------------------------------------------------------ minting

const label = ref('')
const note = ref('')
const channel = ref('')
const minting = ref(false)
const mintFault = ref<string | null>(null)
const minted = ref<ShareMintResult | null>(null)

async function mint() {
  if (minting.value || label.value.trim().length === 0) return
  minting.value = true
  mintFault.value = null
  try {
    minted.value = await opsFetch<ShareMintResult>('/api/ops/share', {
      method: 'POST',
      body: { label: label.value, note: note.value, channel: channel.value },
    })
    label.value = ''
    note.value = ''
    channel.value = ''
    await refresh()
  } catch (err) {
    mintFault.value = (err as OpsFetchError).message
  } finally {
    minting.value = false
  }
}

// ------------------------------------------------------------------- detail

const selected = ref<string | null>(null)
const detail = ref<ShareLinkDetail | null>(null)
const detailFault = ref<OpsFetchError | null>(null)
const detailLoading = ref(false)
let detailSeq = 0

async function loadDetail(token: string) {
  const my = ++detailSeq
  detailLoading.value = true
  detailFault.value = null
  try {
    const res = await opsFetch<ShareLinkDetail>(`/api/ops/share/${token}`)
    if (my !== detailSeq) return
    detail.value = res
  } catch (err) {
    if (my !== detailSeq) return
    detail.value = null
    detailFault.value = err as OpsFetchError
  } finally {
    if (my === detailSeq) detailLoading.value = false
  }
}

/** Click the token to expand a link; click it again to collapse. */
async function toggle(token: string) {
  if (selected.value === token) {
    selected.value = null
    detail.value = null
    return
  }
  selected.value = token
  detail.value = null
  await loadDetail(token)
}

async function setRevoked(token: string, revoked: boolean) {
  try {
    await opsFetch(`/api/ops/share/${token}/revoke`, { method: 'POST', body: { revoked } })
    await refresh()
    if (selected.value === token) await loadDetail(token)
  } catch (err) {
    mintFault.value = (err as OpsFetchError).message
  }
}

// -------------------------------------------------------------------- copy

const copied = ref('')
async function copy(text: string, key: string) {
  if (await copyText(text)) {
    copied.value = key
    setTimeout(() => (copied.value = ''), 1500)
  }
}

// ------------------------------------------------------------------- tables

function chips(v: unknown): string[] {
  return Array.isArray(v) ? v.map(String).filter(Boolean) : []
}

/** "3 PEOPLE · 2 ORGS" — the evidence, never a bare verdict. */
function evidence(row: Row): string {
  const readers = Number(row.readers ?? 0)
  const orgs = chips(row.orgs).length
  const bits: string[] = []
  if (readers > 0) bits.push(`${fmt.num(readers)} ${readers === 1 ? 'PERSON' : 'PEOPLE'}`)
  if (orgs > 0) bits.push(`${fmt.num(orgs)} ORG${orgs === 1 ? '' : 'S'}`)
  return bits.join(' · ')
}

const columns: DataColumn[] = [
  { key: 'token', label: 'TOKEN', width: '6em' },
  { key: 'label', label: 'SENT TO', ellipsis: true },
  { key: 'channel', label: 'CHANNEL' },
  { key: 'opens', label: 'OPENS', title: 'every document request carrying the link' },
  { key: 'views', label: 'VIEWS', title: 'opens from a browser, not a preview bot' },
  { key: 'unfurls', label: 'UNFURLS', title: 'link previews generated by a chat / social platform' },
  { key: 'readers', label: 'PEOPLE', title: 'distinct visitor identities among the sessions carrying the link' },
  { key: 'sessions', label: 'SESSIONS' },
  { key: 'platforms', label: 'PLATFORMS', sortable: false },
  { key: 'orgs', label: 'ORGS', sortable: false, ellipsis: true },
  { key: 'countries', label: 'COUNTRIES', sortable: false },
  { key: 'forwarded', label: 'FORWARDED', title: 'more than one reader, or more than one organisation — recipient unknown' },
  { key: 'lastHit', label: 'LAST SEEN', format: v => fmt.dateTime(v), numeric: true, align: 'left' },
  { key: 'createdAt', label: 'MINTED', format: v => fmt.dateTime(v), numeric: true, align: 'left' },
  { key: 'state', label: 'STATE', sortable: false, align: 'center' },
]

const rows = computed<Row[]>(() =>
  (data.value?.links ?? []).map((l: ShareLinkRow) => ({ ...l, state: l.revoked ? 'REVOKED' : 'LIVE' })),
)

const hitColumns: DataColumn[] = [
  { key: 'ts', label: 'WHEN', format: v => fmt.dateTimeSec(v), numeric: true, align: 'left' },
  { key: 'kind', label: 'KIND', format: v => String(v).toUpperCase() },
  { key: 'agent', label: 'PLATFORM' },
  { key: 'as_org', label: 'ORGANIZATION', ellipsis: true },
  { key: 'country', label: 'COUNTRY' },
  { key: 'referrer_host', label: 'REFERRER' },
  { key: 'path', label: 'PATH', ellipsis: true },
]

const hitRows = computed<Row[]>(() => (detail.value?.hits ?? []) as unknown as Row[])

const sessionColumns: DataColumn[] = [
  { key: 'started_at', label: 'STARTED', format: v => fmt.dateTime(v), numeric: true, align: 'left' },
  { key: 'as_org', label: 'ORGANIZATION', ellipsis: true },
  { key: 'country', label: 'COUNTRY' },
  { key: 'device_type', label: 'DEVICE' },
  { key: 'browser', label: 'BROWSER' },
  { key: 'pageviews', label: 'PAGES' },
  { key: 'active_ms', label: 'ACTIVE', format: v => fmt.mmss(v), numeric: true },
  { key: 'max_scroll_pct', label: 'SCROLL %', format: v => fmt.pct(v, 0) },
]

const sessionRows = computed<Row[]>(() => (detail.value?.sessions ?? []) as unknown as Row[])

function sessionTo(row: Row): string {
  return linkTo(`/ops/sessions/${String(row.sid ?? '')}`)
}

const selectedLink = computed<ShareLinkRow | null>(() => detail.value?.link ?? null)
</script>

<template>
  <div class="sh">
    <p class="sh__note label">
      ONE LINK PER NAMED RECIPIENT · NO URL REWRITING · NO PER-VISITOR TOKEN · NO CHAIN · SEVERAL READERS ON ONE LINK = FORWARDED, RECIPIENT UNKNOWN
    </p>

    <Panel title="MINT // A LINK FOR ONE RECIPIENT">
      <form class="sh__mint" @submit.prevent="mint">
        <label class="label" for="sh-label">SENT TO</label>
        <input
          id="sh-label"
          v-model="label"
          data-testid="share-label"
          class="sh__input"
          type="text"
